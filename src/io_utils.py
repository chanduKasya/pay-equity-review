"""
io_utils.py - reading and writing files (CSV, JSON, SQL) and checksums.
"""

import csv
import hashlib
import json
import os

import schema


def write_csv(rows, folder, file_name, field_names):
    """Write a list of dictionaries to a CSV file."""
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, file_name)
    # newline="" and lineterminator="\n" make the file identical on
    # Windows, Mac and Linux. This matters for the checksum comparison.
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=field_names, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    return path


def read_csv(path):
    """Read a CSV file into a list of dictionaries. Every value is text."""
    rows = []
    with open(path, "r", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            rows.append(row)
    return rows


def read_all_tables(csv_folder):
    """Read every input table. Returns: table name -> list of rows."""
    tables = {}
    for table in schema.TABLES:
        tables[table["name"]] = read_csv(os.path.join(csv_folder, table["name"] + ".csv"))
    return tables


def typed_value(value, column_type):
    """Convert a value to its proper type. Empty becomes None (null)."""
    if value == "" or value is None:
        return None
    if column_type == "INTEGER":
        return int(value)
    if column_type == "REAL":
        return float(value)
    return str(value)


def write_json(rows, table, folder):
    """Write one table as a JSON array, with numbers stored as numbers."""
    os.makedirs(folder, exist_ok=True)
    typed_rows = []
    for row in rows:
        typed_row = {}
        for name, column_type in table["columns"]:
            typed_row[name] = typed_value(row[name], column_type)
        typed_rows.append(typed_row)
    path = os.path.join(folder, table["name"] + ".json")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        # One row per line: easy to read and compare, and still valid JSON.
        f.write("[\n")
        for position in range(len(typed_rows)):
            line = json.dumps(typed_rows[position])
            if position < len(typed_rows) - 1:
                line = line + ","
            f.write(line + "\n")
        f.write("]\n")
    return path


def sql_literal(value, column_type):
    value = typed_value(value, column_type)
    if value is None:
        return "NULL"
    if column_type == "TEXT":
        return "'" + value.replace("'", "''") + "'"
    return repr(value)


def write_sql_schema(folder):
    """CREATE TABLE statements with primary and foreign keys."""
    os.makedirs(folder, exist_ok=True)
    lines = ["-- Generated by src/generate.py. SQLite-compatible.", ""]
    for table in schema.TABLES:
        lines.append('CREATE TABLE "' + table["name"] + '" (')
        parts = []
        for name, column_type in table["columns"]:
            parts.append('  "' + name + '" ' + column_type)
        quoted_pk = []
        for name in table["pk"]:
            quoted_pk.append('"' + name + '"')
        parts.append("  PRIMARY KEY (" + ", ".join(quoted_pk) + ")")
        for column, parent_table, parent_column in table["fks"]:
            parts.append('  FOREIGN KEY ("' + column + '") REFERENCES "'
                         + parent_table + '" ("' + parent_column + '")')
        lines.append(",\n".join(parts))
        lines.append(");")
        lines.append("")
    path = os.path.join(folder, "schema.sql")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return path


def write_sql_seed(all_rows, folder):
    """INSERT statements for every table, parents before children."""
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "seed.sql")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("-- Generated by src/generate.py. Run schema.sql first.\n")
        f.write("BEGIN TRANSACTION;\n")
        for table in schema.TABLES:
            for row in all_rows[table["name"]]:
                values = []
                for name, column_type in table["columns"]:
                    values.append(sql_literal(row[name], column_type))
                f.write('INSERT INTO "' + table["name"] + '" VALUES (' + ", ".join(values) + ");\n")
        f.write("COMMIT;\n")
    return path


def sha256_of_file(path):
    """A checksum: the same file content always gives the same value."""
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def write_text(path, text):
    folder = os.path.dirname(path)
    if folder != "":
        os.makedirs(folder, exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)
